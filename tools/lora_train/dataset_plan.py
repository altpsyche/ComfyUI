"""Plan a MULTI-SUBSET kohya dataset config for a modular character LoRA, and print the TOML.

A modular character has several outfits, each in its own subfolder (output/dataset/<char>/<outfit>/),
and trains as ONE LoRA: identity bakes into the always-on token <char>char, each outfit into its own
token <char>_<outfit>. That needs one `[[datasets.subsets]]` per outfit and `keep_tokens=2` (the two
trigger tokens kept first). `dev train` (devtools/train) calls this (like train_config.py) and writes
the returned TOML.

The logic lives here, in pure Python, instead of in PowerShell so it can be unit-tested (the modular
multi-subset path was the riskiest untested code -- see the plan's red flag #7).

Two pure functions:
  balanced_repeats(counts, steps, epochs, batch) -> per-subset num_repeats so each outfit contributes an
      EQUAL share of the step budget regardless of how many frames it has (red flag #6: a 40-frame outfit
      must not dominate a 20-frame one). The identity token -- on every frame of every subset -- still
      accumulates the full budget, so identity stays strong/always-on.
  render_dataset_toml(char, subsets, cfg, keep_tokens) -> the kohya dataset .toml as a string.

Usage:
    python dataset_plan.py --char mira --steps 2000 --epochs 4 --batch 2 \
        --resolution 1024 --bucket-min 768 --bucket-max 1280 --bucket-steps 64 --keep-tokens 2 \
        --subset "C:/ComfyUI/output/dataset/mira/hoodie=24" \
        --subset "C:/ComfyUI/output/dataset/mira/winter=31"
    # optional regularization subset(s): --reg "C:/.../reg/1girl=200=1girl"
"""
from __future__ import annotations
import argparse


def balanced_repeats(counts, steps, epochs, batch):
    """num_repeats per subset so every subset contributes an equal ~steps/N share.

    Mirrors the single-subset formula in devtools/train/cmd.derive_repeats
    (repeats = round(steps * batch / (images * epochs))) but applied to each outfit's EQUAL share of the
    total target, so uneven frame counts don't skew the mix. Always >= 1.
    """
    counts = list(counts)
    n = len(counts)
    if n == 0:
        return []
    share = steps / n                                   # target steps for each outfit
    out = []
    for c in counts:
        if c <= 0:
            raise ValueError(f"subset image count must be > 0, got {c}")
        out.append(max(1, round(share * batch / (c * epochs))))
    return out


def render_dataset_toml(char, subsets, cfg, keep_tokens=2):
    """Render the kohya multi-subset dataset config.

    subsets: list of dicts with keys image_dir, num_repeats, and optionally is_reg (bool) +
             class_tokens (str) for regularization subsets. Paths are emitted with forward slashes.
    cfg:     dict with resolution, batch, min_bucket_reso, max_bucket_reso, bucket_reso_steps.
    """
    if not subsets:
        raise ValueError("render_dataset_toml needs at least one subset")
    lines = [
        f"# AUTO-GENERATED by `dev train` (dataset_plan.py) for character '{char}' -- do not hand-edit.",
        "[general]",
        "shuffle_caption = true",
        f"keep_tokens = {keep_tokens}",
        'caption_extension = ".txt"',
        "",
        "[[datasets]]",
        f"resolution = {cfg['resolution']}",
        f"batch_size = {cfg['batch']}",
        "enable_bucket = true",
        f"min_bucket_reso = {cfg['min_bucket_reso']}",
        f"max_bucket_reso = {cfg['max_bucket_reso']}",
        f"bucket_reso_steps = {cfg['bucket_reso_steps']}",
    ]
    for s in subsets:
        image_dir = str(s["image_dir"]).replace("\\", "/")
        lines += ["", "  [[datasets.subsets]]", f'  image_dir = "{image_dir}"',
                  f"  num_repeats = {int(s['num_repeats'])}"]
        if s.get("is_reg"):
            lines.append("  is_reg = true")
            if s.get("class_tokens"):
                lines.append(f'  class_tokens = "{s["class_tokens"]}"')
    return "\n".join(lines) + "\n"


def _parse_subset(item, *, reg=False):
    # "dir=count" (outfit subset) or "dir=count=class_tokens" (reg subset). Split count off the RIGHT so
    # a path that itself contains '=' (rare on Windows) survives.
    if reg:
        head, _, class_tokens = item.rpartition("=")
        image_dir, _, count = head.rpartition("=")
        if not image_dir or not count:
            raise SystemExit(f"--reg expects dir=count=class_tokens, got {item!r}")
        return image_dir, int(count), class_tokens
    image_dir, _, count = item.rpartition("=")
    if not image_dir or not count:
        raise SystemExit(f"--subset expects dir=count, got {item!r}")
    return image_dir, int(count)


def main():
    ap = argparse.ArgumentParser(description="Render a multi-subset kohya dataset .toml (modular LoRA).")
    ap.add_argument("--char", required=True)
    ap.add_argument("--steps", type=int, required=True)
    ap.add_argument("--epochs", type=int, required=True)
    ap.add_argument("--batch", type=int, required=True)
    ap.add_argument("--resolution", type=int, required=True)
    ap.add_argument("--bucket-min", type=int, required=True)
    ap.add_argument("--bucket-max", type=int, required=True)
    ap.add_argument("--bucket-steps", type=int, required=True)
    ap.add_argument("--keep-tokens", type=int, default=2)
    ap.add_argument("--subset", action="append", default=[], metavar="dir=count",
                    help="an outfit subfolder + its image count (repeatable)")
    ap.add_argument("--reg", action="append", default=[], metavar="dir=count=class_tokens",
                    help="optional regularization subfolder (repeatable); num_repeats=1, is_reg=true")
    args = ap.parse_args()

    parsed = [_parse_subset(s) for s in args.subset]
    if not parsed:
        raise SystemExit("at least one --subset is required")
    repeats = balanced_repeats([c for _, c in parsed], args.steps, args.epochs, args.batch)
    subsets = [{"image_dir": d, "num_repeats": r} for (d, _), r in zip(parsed, repeats)]
    for item in args.reg:
        d, _, class_tokens = _parse_subset(item, reg=True)
        subsets.append({"image_dir": d, "num_repeats": 1, "is_reg": True, "class_tokens": class_tokens})

    cfg = {"resolution": args.resolution, "batch": args.batch, "min_bucket_reso": args.bucket_min,
           "max_bucket_reso": args.bucket_max, "bucket_reso_steps": args.bucket_steps}
    print(render_dataset_toml(args.char, subsets, cfg, args.keep_tokens), end="")


if __name__ == "__main__":
    main()
